test('active-topic hints are off by default, including non-1 flag values', t => {
  env(t);
  for (const flag of [undefined, '6', 'true', '1']) {
    if (flag === undefined) delete process.env.ZULIP_ACTIVE_TOPICS; else process.env.ZULIP_ACTIVE_TOPICS = flag;
    const { adapter, calls } = fixture(t);
    const cache = (adapter as any).activeTopics;
    const incoming = { channelId: 'zulip:general', messageId: '7', content: [], metadata: {} };
    assert.equal(cache.limit, flag === '1' ? 6 : 0);
    if (flag !== '1') {
      assert.deepEqual(cache.decorate(incoming, 12), incoming);
      assert.equal(calls.length, 0);
    }
  }
});

test('queue registration and poll callbacks are opt-in independently of stream modes', async t => {
  env(t);
  for (const mode of [undefined, 'list', 'subscribed', 'public'] as const) {
    for (const polls of [false, true]) {
      process.env.ZULIP_POLLS = polls ? '1' : '0';
      let delivered = 0, polled = false;
      const loop = new ZulipEventLoop({ streamsMode: mode });
      const { api, calls } = standInApi({
        'POST /register': { result: 'success', queue_id: 'q', last_event_id: -1 },
        'GET /events': () => { if (polled) { loop.stop(); return { result: 'success', events: [] }; } polled = true; return { result: 'success', events: [{ id: 1, type: 'submessage', msg_type: 'widget', content: '{}', message_id: 7, submessage_id: 2, sender_id: 9 }] }; },
      });
      await loop.start(api, () => {}, undefined, undefined, undefined, () => { delivered++; });
      assert.deepEqual(calls[0].params.event_types, ['message', 'reaction', 'update_message', 'delete_message', 'stream', ...(polls ? ['submessage'] : []), ...(['subscribed', 'public'].includes(mode ?? '') ? ['subscription'] : [])]);
      assert.equal(calls[0].params.all_public_streams, mode !== 'subscribed');
      assert.equal(delivered, polls ? 1 : 0);
    }
  }
});


test('default MCPL capabilities are byte-identical to base; poll ontology requires exactly 1', t => {
  env(t);
  const snapshot = readFileSync(new URL('./fixtures/upstream-a2bfec12-capabilities.json', import.meta.url), 'utf8');
  for (const flag of [undefined, '0', 'true']) {
    if (flag === undefined) delete process.env.ZULIP_POLLS; else process.env.ZULIP_POLLS = flag;
    assert.equal(JSON.stringify([false, true].map(typing => buildServerCapabilities({ typing })), null, 2) + '\n', snapshot);
  }
  process.env.ZULIP_POLLS = '1';
  const manifest = buildServerCapabilities({ typing: true }) as any;
  assert.ok(manifest.featureSets['zulip.messaging'].tagOntology.tags['zulip:poll-vote']);
});

