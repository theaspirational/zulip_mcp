test('optional tools require exactly 1; disabled calls perform no requests', async t => {
  env(t);
  const { tools, calls } = fixture(t);
  for (const name of ['send_poll', 'get_poll_results', 'vote_poll']) {
    await assert.rejects(tools.handleToolCall(name, {}), /Unknown tool/);
  }
  assert.equal(calls.length, 0);
  const base = toolDefinitionsForEnv({});
  assert.deepEqual(toolDefinitionsForEnv({ ZULIP_POLLS: 'true', ZULIP_MOVE_MESSAGES: 'true' }), base);
  assert.deepEqual(toolDefinitionsForEnv({ ZULIP_POLLS: '1' }).slice(base.length).map(t => t.name), ['send_poll', 'get_poll_results', 'vote_poll']);
  assert.ok(base.some(t => t.name === 'move_messages'), 'native upstream moves are always available');
  assert.deepEqual(toolDefinitionsForEnv({ ZULIP_MOVE_MESSAGES: '1' }), base);
  for (const tool of withToolClasses(toolDefinitionsForEnv({ ZULIP_POLLS: '1', ZULIP_MOVE_MESSAGES: '1' })).slice(base.length)) assert.deepEqual(tool._meta?.['mcpl/class'], ['comms']);
  const properties = (mode?: string) => toolDefinitionsForEnv({}, mode).find(t => t.name === 'fetch_attachment')!.inputSchema.properties as any;
  assert.equal(properties().message_id, undefined);
  assert.equal(properties('list').message_id, undefined);
  assert.equal(properties('public').message_id, undefined);
  assert.ok(properties('subscribed').message_id);
});

