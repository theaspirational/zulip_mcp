function env(t: any, values: Record<string, string | undefined> = {}) {
  for (const key of new Set(['ZULIP_POLLS', 'ZULIP_MOVE_MESSAGES', 'ZULIP_ACTIVE_TOPICS', 'ZULIP_STREAMS_MODE', ...Object.keys(values)])) {
    const before = process.env[key];
    if (values[key] === undefined) delete process.env[key]; else process.env[key] = values[key];
    t.after(() => { if (before === undefined) delete process.env[key]; else process.env[key] = before; });
  }
}
function fixture(t: any, config: NodeJS.ProcessEnv = {}) {
  const { api, calls } = standInApi({ 'POST /messages': { result: 'success', id: 8 } });
  const dir = mkdtempSync(join(tmpdir(), 'opt-in-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const filters = new FiltersPlane(join(dir, 'filters.json'), config);
  t.after(() => filters.subscriptions.stop());
  const tools = new ZulipToolRuntime({ api, selfUserId: 1, realm: 'https://alpha.example.invalid', authHeader: '', sessionId: 'test' }, dir);
  const adapter = new ZulipAdapter(api, 1, 'test', { filters });
  const server = new ZulipMcplServer(adapter, tools, { serverInfo: { name: 'test', version: '1' }, filters, stateDir: null });
  return { server, tools, adapter, calls };
}

